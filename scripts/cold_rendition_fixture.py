"""Attempt-owned input barrier for real cold music encoders (stdlib only).

Ordinary encodes exec FFmpeg unchanged. Opted-in cold journeys feed real PCM
but withhold the final two seconds until the browser proves playback while
the job is unfinished. No output bytes, job states or browser clocks are faked.
"""

import errno
import hashlib
import io
import json
import os
import select
import signal
import subprocess
import time
import wave
from pathlib import Path

OUTPUTS = {"encoded.mp3", "encoded.ogg", "encoded.flac", "encoded.m4a", "encoded.opus"}


def save(path, value):
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value) + "\n")
    temporary.chmod(0o600)
    temporary.replace(path)


class ColdRenditions:
    def __init__(self, directory, *, timeout=90):
        self.directory = Path(directory)
        self.directory.mkdir(mode=0o700)
        self.active = self.directory / "active.json"
        self.timeout = timeout
        self.case = None
        self.attempt = None

    def begin(self, case, enabled):
        self.active.unlink(missing_ok=True)
        self.case = case
        self.attempt = None
        if enabled:
            self.attempt = self.directory / hashlib.sha256(case.encode()).hexdigest()
            self.attempt.mkdir(mode=0o700)
            save(self.active, {"directory": str(self.attempt), "timeout": self.timeout})

    def release(self, case):
        if case != self.case or self.attempt is None:
            raise RuntimeError("Cold encoder release has no matching fixture owner")
        record = json.loads((self.attempt / "encoder.json").read_text())
        if record["state"] != "held" or (self.attempt / "release").exists():
            raise RuntimeError("Cold encoder must be held and released exactly once")
        (self.attempt / "release").touch(exist_ok=False)

    def end(self):
        # The owning application and its children have already been reaped.
        record = None
        if self.attempt and (self.attempt / "encoder.json").exists():
            record = json.loads((self.attempt / "encoder.json").read_text())
        self.active.unlink(missing_ok=True)
        self.case = self.attempt = None
        return record


def encode(real, active, arguments):
    active = Path(active)
    if not active.exists() or Path(arguments[-1]).name not in OUTPUTS:
        os.execv(real, [real, *arguments])
    control = json.loads(active.read_text())
    directory = Path(control["directory"])
    # Exactly one real encoder belongs to this cold journey. A duplicate must
    # fail instead of silently borrowing another job's release receipt.
    (directory / "claimed").touch(exist_ok=False)
    record_path = directory / "encoder.json"
    record = {"state": "starting", "output": Path(arguments[-1]).name}
    child = None
    descriptor = None
    fifo = directory / "input.wav"
    began = time.monotonic()

    def interrupt(signum, _frame):
        raise InterruptedError(f"Cold encoder received signal {signum}")

    signal.signal(signal.SIGTERM, interrupt)
    signal.signal(signal.SIGINT, interrupt)
    try:
        index = arguments.index("-i") + 1
        # This fixture deliberately accepts only the real WAV generated by
        # freshMusicAudio. Unsupported sources fail rather than lose the gate.
        with wave.open(arguments[index], "rb") as source:
            params = source.getparams()
            if params.comptype != "NONE" or params.nframes < params.framerate * 10:
                raise ValueError(
                    "Cold fixture requires at least ten seconds of PCM WAV"
                )
            pcm = source.readframes(params.nframes)
        canonical = io.BytesIO()
        with wave.open(canonical, "wb") as output:
            output.setparams(params)
            output.writeframes(pcm)
        payload = canonical.getvalue()
        tail = params.framerate * params.nchannels * params.sampwidth * 2
        command = arguments.copy()
        # Keep production's file-only protocol whitelist intact. A private
        # named FIFO provides streaming input through that same local protocol.
        os.mkfifo(fifo, 0o600)
        command[index] = str(fifo)
        child = subprocess.Popen([real, "-nostdin", *command], stdin=subprocess.DEVNULL)
        record.update(
            pid=child.pid, input_frames=params.nframes, held_frames=params.framerate * 2
        )
        deadline = began + control["timeout"]
        while descriptor is None:
            if child.poll() is not None or time.monotonic() >= deadline:
                raise RuntimeError("Cold encoder did not open its owned input FIFO")
            try:
                descriptor = os.open(fifo, os.O_WRONLY | os.O_NONBLOCK)
            except OSError as error:
                if error.errno != errno.ENXIO:
                    raise
                time.sleep(0.01)

        def feed(data):
            pending = memoryview(data)
            while pending:
                if child.poll() is not None:
                    raise RuntimeError("Cold encoder exited before consuming input")
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise TimeoutError("Cold encoder input deadline exceeded")
                if select.select([], [descriptor], [], min(remaining, 0.1))[1]:
                    pending = pending[os.write(descriptor, pending[:65536]) :]

        feed(payload[:-tail])
        record.update(state="held", ready_seconds=time.monotonic() - began)
        save(record_path, record)
        while not (directory / "release").exists():
            if child.poll() is not None:
                raise RuntimeError("Cold encoder exited before browser release")
            if time.monotonic() >= deadline:
                raise TimeoutError("Browser never released the cold encoder")
            time.sleep(0.01)
        if child.poll() is not None:
            raise RuntimeError("Cold encoder died before consuming its held tail")
        record.update(state="released", release_seconds=time.monotonic() - began)
        save(record_path, record)
        feed(payload[-tail:])
        os.close(descriptor)
        descriptor = None
        code = child.wait(timeout=30)
        if code:
            raise RuntimeError(f"Cold encoder failed with exit {code}")
        record.update(state="complete", elapsed_seconds=time.monotonic() - began)
        save(record_path, record)
    except BaseException as error:
        record.update(state="failed", error=str(error))
        save(record_path, record)
        raise
    finally:
        if child is not None and child.poll() is None:
            child.terminate()
            try:
                child.wait(timeout=2)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait(timeout=2)
        if descriptor is not None:
            os.close(descriptor)
        fifo.unlink(missing_ok=True)
