async function audit(page,noScript){
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  if(!noScript){
    const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
    expect(result.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}))).toEqual([]);
  }
}
async function artwork(page,slot){
  const previous=await page.locator('img.music-artwork').count();
  await openDetailsFor(page.getByText('Change artwork',{exact:true}));
  await page.getByLabel(slot==='cover'?'Cover file':'Image file',{exact:true}).setInputFiles(process.env.A11Y_POSTER_FIXTURE);
  await page.getByRole('button',{name:slot==='cover'?'Upload cover':'Upload image',exact:true}).press('Enter');
  await expect(page.locator('img.music-artwork')).toHaveCount(previous+1);
  const image=page.getByRole('img',{name:new RegExp(slot==='cover'?': Cover artwork$':': Image$')});
  await expect.poll(()=>image.evaluate(img=>img.complete && img.naturalWidth>0)).toBe(true);
  return new URL(await image.getAttribute('src'),page.url()).href;
}
async function albumAccess(owner,url,visibility,shareTracks){
  await owner.goto(url);
  await openDetailsFor(owner.getByRole('link',{name:'Manage album access',exact:true,includeHidden:true}));
  await owner.getByRole('link',{name:'Manage album access',exact:true}).press('Enter');
  await owner.getByLabel('Who can view album details',{exact:true}).selectOption(visibility);
  if(shareTracks!==undefined)await owner.getByRole('checkbox',{name:'Also share my tracks',exact:true}).setChecked(shareTracks);
  const action=new URL(owner.url()).pathname.replace('/music/','/web/music/');
  const posted=owner.waitForResponse(response=>response.request().method()==='POST'&&new URL(response.url()).pathname===action);
  await owner.getByRole('button',{name:'Save album access',exact:true}).press('Enter');
  const response=await posted;
  expect(response.status()).toBe(303);
  await owner.goto(response.headers().location);
}
